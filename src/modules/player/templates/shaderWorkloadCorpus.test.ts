import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { performance } from 'node:perf_hooks'
import { describe, expect, it } from 'vitest'
import { compileShader } from '@notrac/mage/compiler'
import { analyzeCompiledShader, normalizeCompiledShader, SHADER_WORKLOAD_LIMITS } from '@notrac/mage/compiled-shader'
import baseline from '../../../../contracts/scenes/shader-workload.v1.fixtures.json'
import catalog from '../../../../contracts/scenes/builder-catalog.v1.fixtures.json'
import { compileBuilderDocument, compileBuilderPreviewDocument } from './builderCompiler'
import { parseSceneDocument, type BuilderSceneDocument } from './sceneContract'
import { resolveSceneForPlayback } from './resolveScene'
import { SHADER_WORKLOAD_CORPUS_VERSION, shaderWorkloadCorpus } from './shaderWorkloadCorpus.fixtures'

const hash = (value: string) => createHash('sha256').update(value).digest('hex')

describe('PL-03 supported workload corpus', () => {
  it('accepts every original, saved and preview design without changing the compiled artifact', () => {
    const rows = shaderWorkloadCorpus().map(entry => {
      const artifact = compileShader(entry.source, { maxRaymarchIterations: 200 })
      const { artifact: normalized, workload } = analyzeCompiledShader(artifact, { maxRaymarchIterations: 200 })
      const durations = []
      for (let sample = 0; sample < (process.env.PL03_WORKLOAD_REPORT ? 7 : 1); sample++) {
        const start = performance.now()
        normalizeCompiledShader(artifact, { maxRaymarchIterations: 200 })
        durations.push(performance.now() - start)
      }
      durations.sort((a, b) => a - b)
      expect(normalized, entry.id).toEqual(artifact)
      expect(workload.fragmentCost, entry.id).toBeLessThanOrEqual(SHADER_WORKLOAD_LIMITS.fragmentCost)
      const canonical = { ...artifact }
      // Rebuilding the package on another OS may change CRLF spelling in the
      // pinned GLSL scaffold. Preserve every other byte and all uniform values.
      for (const key of ['frag', 'vert', 'geoGLSL', 'colorGLSL'] as const) {
        canonical[key] = canonical[key].replaceAll('\r\n', '\n').replaceAll('\r', '\n')
      }
      return { id: entry.id, label: entry.label, sourceSha256: hash(entry.source),
        artifactSha256: hash(JSON.stringify(canonical)), workload,
        validationMedianMs: Number(durations[Math.floor(durations.length / 2)].toFixed(3)),
        validationP95Ms: Number(durations[Math.ceil(durations.length * .95) - 1].toFixed(3)) }
    })
    expect(rows.filter(row => row.id.endsWith('/original'))).toHaveLength(14)
    expect(rows).toHaveLength(86)
    expect(baseline.corpusVersion).toBe(SHADER_WORKLOAD_CORPUS_VERSION)
    expect(rows.map(({ id, sourceSha256, artifactSha256 }) => ({ id, sourceSha256, artifactSha256 })))
      .toEqual(baseline.entries)
    if (process.env.PL03_WORKLOAD_REPORT) {
      writeFileSync(process.env.PL03_WORKLOAD_REPORT, `${JSON.stringify({
        corpusVersion: SHADER_WORKLOAD_CORPUS_VERSION, measuredAt: new Date().toISOString(),
        runtime: `${process.platform}/${process.arch} Node ${process.version}`,
        samplesPerCase: 7, limits: SHADER_WORKLOAD_LIMITS, rows,
      }, null, 2)}\n`)
    }
  }, 30_000)

  it('keeps Original and Selective on identical unchanged Builder shader designs', () => {
    for (const fixture of catalog.recipes) {
      const document = parseSceneDocument(fixture.document) as BuilderSceneDocument
      for (const compile of [compileBuilderDocument, compileBuilderPreviewDocument]) {
        const original = compile({ ...document, settings: { ...document.settings, audioResponse: 'legacy' } })
        const selective = compile({ ...document, settings: { ...document.settings, audioResponse: 'mapped-v1' } })
        expect(original.shader, fixture.label).toBe(selective.shader)
        expect(original.uniforms, fixture.label).toEqual(selective.uniforms)
      }
    }
  })

  it.skipIf(!process.env.PL03_SAVED_SCENES)('accepts a read-only local saved-scene snapshot without modifying its data', () => {
    const scenes = JSON.parse(readFileSync(process.env.PL03_SAVED_SCENES!, 'utf8')) as { sceneId: number; sceneData: unknown }[]
    const before = JSON.stringify(scenes)
    const results = scenes.map(scene => {
      const document = parseSceneDocument(scene.sceneData)
      // This tool never executes custom source from a database. Builder source
      // is generated by the allowlisted data compiler; templates are checked in.
      expect(document.kind, `Scene ${scene.sceneId}: custom source must use a disposable worker`).not.toBe('custom')
      if (document.kind === 'custom') throw new Error('Custom scenes require isolated worker validation.')
      const { engineScene } = resolveSceneForPlayback(document)
      const shader = (engineScene.visualizer as { shader: string }).shader
      const artifact = compileShader(shader, { maxRaymarchIterations: 200 })
      const { workload } = analyzeCompiledShader(artifact, { maxRaymarchIterations: 200 })
      return { sceneId: scene.sceneId, documentSha256: hash(JSON.stringify(scene.sceneData)), workload }
    })
    expect(JSON.stringify(scenes)).toBe(before)
    if (process.env.PL03_SAVED_REPORT) {
      writeFileSync(process.env.PL03_SAVED_REPORT, `${JSON.stringify({ corpusVersion: 1, results }, null, 2)}\n`)
    }
  })
})
