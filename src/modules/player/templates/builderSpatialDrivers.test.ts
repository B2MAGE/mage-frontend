import { describe, expect, it } from 'vitest'
import { compileShader } from '@notrac/mage/compiler'
import { compileBuilderDocument } from './builderCompiler'
import { parseSceneDocument, type BuilderDriverSource, type BuilderSceneDocument } from './sceneContract'

type Vector = { x: number; y: number; z: number }
type Value = number | Vector
const vector = (x: number, y = x, z = x): Vector => ({ x, y, z })
const axes = ['x', 'y', 'z'] as const

/** Evaluate only the packaged compiler's coordinate/scalar prefix up to the first sphere.
 * This deliberately rejects unknown instructions instead of implementing a second renderer.
 */
function sampleRadius(scene: BuilderSceneDocument, point: Vector, ray = vector(0, 0, -1)) {
  const artifact = compileShader(compileBuilderDocument(scene).shader)
  const body = artifact.geoGLSL.slice(artifact.geoGLSL.lastIndexOf('float surfaceDistance'))
  const values: Record<string, Value> = { p: point }
  const evaluate = (source: string): Value => {
    const binary = source.match(/^\((\w+)([+/])(\w+)\)$/)
    if (binary && (typeof values[binary[1]] === 'object' || typeof values[binary[3]] === 'object')) {
      const left = values[binary[1]], right = values[binary[3]]
      return Object.fromEntries(axes.map(axis => {
        const a = typeof left === 'number' ? left : left[axis]
        const b = typeof right === 'number' ? right : right[axis]
        return [axis, binary[2] === '+' ? a + b : a / b]
      })) as Vector
    }
    // The input is generated by our trusted compiler from the fixed fixtures below.
    return new Function(...Object.keys(values), 'vec3', 'getRayDirection', 'min', 'max', 'floor',
      `return ${source};`)(...Object.values(values), vector, () => ray, Math.min, Math.max, Math.floor) as Value
  }
  for (const raw of body.split('\n').slice(1)) {
    const line = raw.trim()
    if (!line) continue
    const sphere = line.match(/^float prim_\d+ = sphere\(\w+, ([^;]+)\);$/)
    if (sphere) return evaluate(sphere[1]) as number
    const declaration = line.match(/^(?:float|vec3) (\w+) = (.+);$/)
    if (declaration) { values[declaration[1]] = evaluate(declaration[2]); continue }
    const displace = line.match(/^(\w+) -= (vec3\(.+\));$/)
    if (displace) {
      const current = values[displace[1]] as Vector, offset = evaluate(displace[2]) as Vector
      values[displace[1]] = vector(current.x - offset.x, current.y - offset.y, current.z - offset.z)
      continue
    }
    const rotation = line.match(/^(\w+)\.([xyz])([xyz]) = \1\.\2\3\*rot2\((.+)\);$/)
    if (rotation) {
      const current = values[rotation[1]] as Vector, first = rotation[2] as keyof Vector, second = rotation[3] as keyof Vector
      const angle = evaluate(rotation[4]) as number, cosine = Math.cos(angle), sine = Math.sin(angle)
      values[rotation[1]] = { ...current, [first]: current[first] * cosine + current[second] * sine,
        [second]: -current[first] * sine + current[second] * cosine }
      continue
    }
    const assignment = line.match(/^(\w+) = (.+);$/)
    if (assignment) { values[assignment[1]] = evaluate(assignment[2]); continue }
    throw new Error(`Unsupported coordinate probe instruction: ${line}`)
  }
  throw new Error('No sphere radius reached in compiled shader')
}

function fixture(source: BuilderDriverSource, grouped = false): BuilderSceneDocument {
  return parseSceneDocument({ schemaVersion: 1, kind: 'builder', builderVersion: 1,
    objects: [{ id: 'shape', operation: { type: 'sphere' }, transform: { position: { x: .3 }, scale: { x: 2 } },
      drivers: [{ target: 'operation.radius', mode: 'replace', expression: { type: 'component', axis: 'x', input: { type: 'input', source } } }] }],
    ...(grouped ? { composition: { version: 1, roots: ['outer'], groups: [
      { id: 'outer', children: ['inner'], transform: { position: { x: 1 }, scale: 2 } },
      { id: 'inner', children: ['shape'], transform: { position: { x: .4 }, scale: 3 } },
    ] } } : {}),
  }) as BuilderSceneDocument
}

describe('compiled Builder spatial input coordinates', () => {
  it('reads distinct world, nearest parent and baseline local positions through nested groups', () => {
    const point = vector(4.8, 0, 0)
    expect(sampleRadius(fixture('world-position', true), point)).toBeCloseTo(4.8)
    expect(sampleRadius(fixture('group-position', true), point)).toBeCloseTo(.5)
    expect(sampleRadius(fixture('local-position', true), point)).toBeCloseTo(.1)
  })

  it('falls back to world coordinates when an object has no parent group', () => {
    const point = vector(.8, 0, 0)
    expect(sampleRadius(fixture('group-position'), point)).toBeCloseTo(.8)
    expect(sampleRadius(fixture('world-position'), point)).toBeCloseTo(.8)
    expect(sampleRadius(fixture('local-position'), point)).toBeCloseTo(.25)
  })

  it('keeps parent coordinates shared while local position follows each arrangement copy', () => {
    const local = fixture('local-position', true), parent = fixture('group-position', true)
    for (const scene of [local, parent]) scene.objects[0].arrangements = [{ type: 'linear', axis: 'x', count: 2, spacing: .4 }]
    // First copy is centered at .3 - .2 in its parent frame.
    expect(sampleRadius(local, vector(4.8, 0, 0))).toBeCloseTo(.2)
    expect(sampleRadius(parent, vector(4.8, 0, 0))).toBeCloseTo(.5)
  })

  it('uses transformed parent axes and scales for a rotated group', () => {
    const scene = fixture('group-position', true)
    scene.composition!.groups[1].transform.rotation.z = Math.PI / 2
    // Outer local point is (.4, 1.5); inner inverse transform makes it (.5, 0).
    expect(sampleRadius(scene, vector(1.8, 3, 0))).toBeCloseTo(.5)
  })

  it.each([
    ['world-position', 4.8], ['group-position', 1.9], ['local-position', .5],
  ] as const)('evaluates a group’s %s before its own driven transform', (source, scale) => {
    const scene = fixture('local-position', true)
    scene.objects[0].transform.position.x = 0
    scene.objects[0].transform.scale.x = 1
    scene.composition!.groups[1].drivers = [{ target: 'scale', mode: 'replace',
      expression: { type: 'component', axis: 'x', input: { type: 'input', source } } }]
    // The inner group's parent is the outer frame, while its own baseline
    // local coordinate is (1.9 - .4) / 3. Its driver must not feed back on itself.
    expect(sampleRadius(scene, vector(4.8, 0, 0))).toBeCloseTo(1.5 / scale)
  })

  it('takes view ray from camera direction, independent of sampled position or parent transforms', () => {
    const scene = fixture('view-ray', true)
    const firstRay = vector(.3, .4, -Math.sqrt(.75)), secondRay = vector(.6, 0, -.8)
    expect(sampleRadius(scene, vector(4.8, 0, 0), firstRay)).toBeCloseTo(.3)
    expect(sampleRadius(scene, vector(20, -7, 3), firstRay)).toBeCloseTo(.3)
    expect(sampleRadius(scene, vector(4.8, 0, 0), secondRay)).toBeCloseTo(.6)
  })
})
