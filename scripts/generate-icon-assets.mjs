import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import { ChevronDown } from 'lucide-react'

// A native select cannot contain a React icon. Generate its CSS asset from
// the same package as AppIcon instead of maintaining another SVG by hand.
const assetDirectory = new URL('../src/shared/ui/assets/', import.meta.url)
const require = createRequire(import.meta.url)
const packageDirectory = dirname(require.resolve('lucide-react/package.json'))
const svg = renderToStaticMarkup(createElement(ChevronDown, { size: 24, color: '#a4a8b2' }))
mkdirSync(assetDirectory, { recursive: true })
writeFileSync(new URL('chevron-down.svg', assetDirectory), `<!-- Generated by scripts/generate-icon-assets.mjs from lucide-react. See lucide-LICENSE.txt. -->\n${svg}\n`)
writeFileSync(new URL('lucide-LICENSE.txt', assetDirectory), readFileSync(join(packageDirectory, 'LICENSE')))
